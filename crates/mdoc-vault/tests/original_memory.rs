//! A 256 MiB Source Original round-trips in bounded memory (#1091,
//! ROADMAP Vault & Projects item 3), checked by its shape on every
//! platform: the import seals chunks to disk while it still reads the
//! source, the read hands back plaintext before it reaches the file's end,
//! and neither moves more than a chunk at a time. On Linux the process's
//! peak resident memory is checked too. A precise heap count would need a
//! test allocator, which the workspace's `unsafe` fence (#897) rules out.
use mdoc_vault::{DocumentOrigin, NewDocument, OriginalInfo, SourceKind, Vault};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{self, Read, Seek, SeekFrom, Write},
    path::{Path, PathBuf},
};

const MIB: usize = 1 << 20;
const SIZE: u64 = 256 * MIB as u64;
/// The most an import may read of its source at once: a chunk and the byte
/// that tells whether more follows.
const MAX_READ: usize = MIB + 1;

/// SplitMix64: a different word for every index.
fn mix(index: u64) -> u64 {
    let mut z = index.wrapping_add(1).wrapping_mul(0x9e37_79b9_7f4a_7c15);
    z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    z ^ (z >> 31)
}

/// The import's in-progress file, wherever in `docs/` it is.
fn importing(root: &Path) -> u64 {
    let Ok(dirs) = fs::read_dir(root.join("docs")) else {
        return 0;
    };
    let files = dirs
        .flatten()
        .flat_map(|dir| fs::read_dir(dir.path()).into_iter().flatten());
    files
        .flatten()
        .filter(|file| file.file_name().to_string_lossy().starts_with(".import-"))
        .filter_map(|file| fs::metadata(file.path()).ok())
        .map(|metadata| metadata.len())
        .sum()
}

/// `SIZE` generated bytes, never held anywhere. At each read it notes how
/// much it has handed out and how much of the sealed file is on disk.
struct Source {
    root: PathBuf,
    pos: u64,
    word: [u8; 8],
    hasher: Sha256,
    largest_read: usize,
    /// (bytes handed out, bytes of the sealed file on disk), at each read.
    seen: Vec<(u64, u64)>,
}

impl Read for Source {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        self.largest_read = self.largest_read.max(buf.len());
        self.seen.push((self.pos, importing(&self.root)));
        let left = usize::try_from(SIZE - self.pos).unwrap_or(usize::MAX);
        let n = buf.len().min(left);
        for byte in &mut buf[..n] {
            let at = (self.pos % 8) as usize;
            if at == 0 {
                self.word = mix(self.pos / 8).to_le_bytes();
            }
            *byte = self.word[at];
            self.pos += 1;
        }
        self.hasher.update(&buf[..n]);
        Ok(n)
    }
}

/// Where the read's plaintext goes: hashed, never kept.
struct Sink {
    hasher: Sha256,
    len: u64,
    largest_write: usize,
}

impl Write for Sink {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        self.largest_write = self.largest_write.max(buf.len());
        self.hasher.update(buf);
        self.len += buf.len() as u64;
        Ok(buf.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

/// The process's peak resident memory in KiB.
#[cfg(target_os = "linux")]
fn peak_resident_kib() -> u64 {
    let status = fs::read_to_string("/proc/self/status").unwrap();
    let line = status.lines().find(|l| l.starts_with("VmHWM:")).unwrap();
    line.split_whitespace().nth(1).unwrap().parse().unwrap()
}

#[test]
fn a_256_mib_original_round_trips_in_bounded_memory() {
    #[cfg(target_os = "linux")]
    let peak_before = peak_resident_kib();
    let temp = tempfile::tempdir().unwrap();
    let root = temp.path().join("vault");
    let vault = Vault::open(&root, &[7; 32]).unwrap();
    let new = NewDocument {
        project: None,
        title: "Large".into(),
        source_kind: SourceKind::Pdf,
        origin: DocumentOrigin::Ordinary,
        markdown: String::new(),
    };
    let info = OriginalInfo {
        file_name: "large.pdf".into(),
        ..OriginalInfo::default()
    };
    let mut source = Source {
        root: root.clone(),
        pos: 0,
        word: [0; 8],
        hasher: Sha256::new(),
        largest_read: 0,
        seen: Vec::new(),
    };
    let document = vault.import_document(new, &mut source, info).unwrap();
    let original = document.original.clone().unwrap();
    assert_eq!(original.len, SIZE);
    let source_hash: String = (source.hasher.finalize().iter())
        .map(|b| format!("{b:02x}"))
        .collect();
    assert_eq!(original.sha256, source_hash);

    // The import read a chunk at a time and sealed each one to disk before
    // reading far past it: by the source's end, all but the last couple of
    // chunks were on disk.
    assert!(source.largest_read <= MAX_READ, "{}", source.largest_read);
    for &(handed, on_disk) in &source.seen {
        assert!(
            on_disk + 2 * MIB as u64 >= handed,
            "{handed} bytes read with {on_disk} on disk"
        );
    }
    assert!(source.seen.len() > 200, "{} reads", source.seen.len());

    // The read hands back at most a chunk per call, however large the
    // buffer, and the bytes are the source's.
    let mut reader = vault.open_original(&document.id).unwrap();
    let mut sink = Sink {
        hasher: Sha256::new(),
        len: 0,
        largest_write: 0,
    };
    let mut buf = vec![0; 8 * MIB];
    loop {
        let n = reader.read(&mut buf).unwrap();
        if n == 0 {
            break;
        }
        sink.write_all(&buf[..n]).unwrap();
    }
    assert!(sink.largest_write <= MIB, "{}", sink.largest_write);
    assert_eq!(sink.len, SIZE);
    let read_hash: String = (sink.hasher.finalize().iter())
        .map(|b| format!("{b:02x}"))
        .collect();
    assert_eq!(read_hash, original.sha256);

    // The first plaintext comes before the read reaches the file's end:
    // damage the last byte after the first chunk is out, and the read
    // fails only at the end.
    let mut reader = vault.open_original(&document.id).unwrap();
    let first = reader.read(&mut buf).unwrap();
    assert!(first > 0 && first <= MIB, "{first}");
    let file = root.join("docs").join(&document.id).join("original.enc");
    let mut sealed = fs::File::options()
        .read(true)
        .write(true)
        .open(&file)
        .unwrap();
    sealed.seek(SeekFrom::End(-1)).unwrap();
    let mut last = [0];
    sealed.read_exact(&mut last).unwrap();
    sealed.seek(SeekFrom::End(-1)).unwrap();
    sealed.write_all(&[last[0] ^ 1]).unwrap();
    sealed.sync_all().unwrap();
    let mut handed = first as u64;
    let error = loop {
        match reader.read(&mut buf) {
            Ok(0) => panic!("the damaged end was not noticed"),
            Ok(n) => handed += n as u64,
            Err(error) => break error,
        }
    };
    assert_eq!(error.kind(), io::ErrorKind::InvalidData);
    assert_eq!(handed, SIZE - MIB as u64, "all chunks but the last");

    #[cfg(target_os = "linux")]
    {
        let grown = peak_resident_kib().saturating_sub(peak_before);
        assert!(grown < 64 * 1024, "peak resident memory grew {grown} KiB");
    }
}
